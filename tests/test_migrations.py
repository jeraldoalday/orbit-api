"""Structural checks on the Alembic revision chain.

These catch the mistakes that only surface at deploy time: two branches created
in parallel leaving multiple heads, a migration that can't be rolled back, or a
model whose table nobody ever wrote a migration for.
"""

import pathlib
import re

import pytest

from alembic.config import Config
from alembic.script import ScriptDirectory
from app.db.base import Base

PROJECT_ROOT = pathlib.Path(__file__).resolve().parent.parent
VERSIONS_DIR = PROJECT_ROOT / "alembic" / "versions"


@pytest.fixture(scope="module")
def script_directory() -> ScriptDirectory:
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT_ROOT / "alembic"))
    return ScriptDirectory.from_config(config)


def test_single_head(script_directory):
    """Parallel branches leave two heads and `alembic upgrade head` then fails."""
    heads = script_directory.get_heads()

    assert len(heads) == 1, f"expected one head, found {heads}"


def test_single_base(script_directory):
    assert len(script_directory.get_bases()) == 1


def test_revision_chain_is_walkable(script_directory):
    head = script_directory.get_current_head()

    revisions = list(script_directory.walk_revisions("base", head))

    assert len(revisions) == len(list(VERSIONS_DIR.glob("*.py")))


def test_revision_ids_are_unique(script_directory):
    revision_ids = [revision.revision for revision in script_directory.walk_revisions()]

    assert len(revision_ids) == len(set(revision_ids))


def test_every_migration_defines_upgrade_and_downgrade():
    for path in sorted(VERSIONS_DIR.glob("*.py")):
        source = path.read_text()
        assert "def upgrade()" in source, f"{path.name} has no upgrade()"
        assert "def downgrade()" in source, f"{path.name} has no downgrade()"


def test_no_downgrade_is_left_as_a_stub():
    """An autogenerated `pass` downgrade is a rollback that silently no-ops."""
    stub = re.compile(r"def downgrade\(\) -> None:\s*\n\s*pass\s*\n")

    for path in sorted(VERSIONS_DIR.glob("*.py")):
        assert not stub.search(path.read_text()), f"{path.name} has a stub downgrade()"


def test_every_model_table_has_a_migration():
    migration_source = "\n".join(
        path.read_text() for path in sorted(VERSIONS_DIR.glob("*.py"))
    )

    # Older migrations were generated with single-quoted names, newer ones
    # with double quotes, so accept either spelling of the table literal.
    missing = [
        table_name
        for table_name in Base.metadata.tables
        if f'"{table_name}"' not in migration_source
        and f"'{table_name}'" not in migration_source
    ]

    assert missing == [], f"tables with no migration: {missing}"
